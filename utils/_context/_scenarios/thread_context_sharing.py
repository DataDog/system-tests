from pathlib import Path

from docker.errors import APIError
from docker.models.networks import Network
from docker.types import Mount
import pytest

from utils import interfaces
from utils._context.constants import WeblogCategory
from utils._logger import logger

from ._core import EndToEndScenario, scenario_groups


CWS_READINESS_TIMEOUT = 90

# Where a Kata docker-in-docker runner mounts the VM's kernel filesystems (source -> agent target)
VM_HOST = "/vm-host"
_GUEST_KERNEL_MOUNTS = {
    "proc": ("/host/proc", True),
    "sys/fs/cgroup": ("/host/sys/fs/cgroup", True),
    "sys/kernel/debug": ("/sys/kernel/debug", False),
    "sys/kernel/tracing": ("/sys/kernel/tracing", False),
    "sys/kernel/security": ("/sys/kernel/security", False),
}

_GUEST_KERNEL_MOUNTS_HELP = (
    f"Using the Kata guest kernel mounts because {VM_HOST} exists. They require a Kata docker-in-docker "
    "job on a GitLab runner that mounts the VM's /proc, /sys/fs/cgroup and /sys/kernel/{debug,tracing,security} "
    f"into the job's containers under {VM_HOST} ({VM_HOST}/proc etc.), such as the micro-vms-cws runner pool."
)


class ThreadContextSharingScenario(EndToEndScenario):
    """Exercises CWS (Cloud Workload Security) thread-context sharing: a tracer that
    implements it publishes the trace_id/span_id of the span active on a thread, so
    that system-probe's runtime security module can stamp them (as dd.trace_id /
    dd.span_id) onto the SECL security event generated by a syscall happening on that
    same thread.

    The weblog contract is documented in docs/understand/weblogs/end-to-end_weblog.md
    under "GET /security/thread_context_sharing". No tracer implements it yet - test
    classes using this scenario should be marked `@missing_feature` per-library until
    each tracer's implementation lands.

    CWS security events are observed through the agent's proxy-captured HTTPS traffic
    (`/api/v2/logs`), decoded via `tests/cws/utils.py` - the same way this scenario
    already observes telemetry, remote config, etc.

    When /vm-host exists, the scenario assumes it runs inside a Kata VM's docker-in-docker
    container, where the kernel filesystems of the VM are mounted under /vm-host by the CI
    runner. See docs/understand/scenarios/thread_context_sharing.md.
    """

    def __init__(self) -> None:
        super().__init__(
            name="THREAD_CONTEXT_SHARING",
            doc=(
                "Check that tracers share the trace_id/span_id of the currently active span with "
                "system-probe, so that CWS (Cloud Workload Security) security events triggered on "
                "the same thread carry them as dd.trace_id/dd.span_id."
            ),
            weblog_categories=[WeblogCategory.dd_trace],
            appsec_enabled=True,
            iast_enabled=False,
            scenario_groups=[scenario_groups.thread_context_sharing],
        )

    def configure(self, config: pytest.Config):
        # checked first, so that an incomplete /vm-host fails before anything else is prepared
        guest_kernel_mounts = self._guest_kernel_mounts_detected()

        super().configure(config)

        agent = self.agent_container

        agent.environment["DD_RUNTIME_SECURITY_CONFIG_ENABLED"] = "true"

        # span_tracking makes system-probe read the tracer's thread context; the self test is
        # the readiness signal the tests wait on (see tests/cws/utils.py).
        agent.environment["DD_RUNTIME_SECURITY_CONFIG_SPAN_TRACKING_ENABLED"] = "true"
        agent.environment["DD_RUNTIME_SECURITY_CONFIG_SELF_TEST_ENABLED"] = "true"

        agent.volumes["./utils/build/docker/agent/runtime-security.d"] = {
            "bind": "/etc/datadog-agent/runtime-security.d",
            "mode": "ro",
        }

        # Required for CWS to see host processes and load eBPF programs. Mirrors
        # datadog-agent's documented Docker setup for Cloud Workload Security:
        # https://docs.datadoghq.com/security/workload_protection/setup/agent/docker/
        agent.pid_mode = "host"
        agent.cgroupns = "host"
        agent.cap_add = [
            "SYS_ADMIN",
            "SYS_RESOURCE",
            "SYS_PTRACE",
            "NET_ADMIN",
            "NET_BROADCAST",
            "IPC_LOCK",
            "CHOWN",
        ]
        agent.security_opt = ["apparmor:unconfined"]
        agent.volumes["/etc/passwd"] = {"bind": "/etc/passwd", "mode": "ro"}
        agent.volumes["/etc/group"] = {"bind": "/etc/group", "mode": "ro"}

        if guest_kernel_mounts:
            self._use_guest_kernel_mounts()
        else:
            # rw: attaching kprobes means writing to /sys/kernel/debug/tracing/kprobe_events
            agent.volumes["/sys/kernel/debug"] = {"bind": "/sys/kernel/debug", "mode": "rw"}
            agent.volumes["/sys/kernel/security"] = {"bind": "/sys/kernel/security", "mode": "rw"}

        # The weblog depends on the agent, so it is only started after this warmup. A weblog
        # started before CWS was live has been observed to produce events without trace context.
        self._guest_kernel_mounts = guest_kernel_mounts
        self._agent_warmup = agent.warmup
        agent.warmup = self._agent_warmup_then_wait_for_cws  # type: ignore[method-assign]

    @staticmethod
    def _guest_kernel_mounts_detected() -> bool:
        """Whether the CI runner provides the Kata VM's kernel filesystems under /vm-host.

        This looks at the filesystem of the pytest process, while the binds are resolved by the
        docker daemon. The two agree on the GitLab Kubernetes executor, which mounts the runner's
        hostPath volumes into every container of the job pod, the DIND service included.
        """
        vm_host = Path(VM_HOST)
        if not vm_host.exists():
            return False
        missing = [path for path in _GUEST_KERNEL_MOUNTS if not (vm_host / path).is_dir()]
        if missing:
            pytest.exit(
                f"{VM_HOST} exists but lacks {', '.join(missing)}. {_GUEST_KERNEL_MOUNTS_HELP}",
                1,
            )
        logger.stdout(f"{VM_HOST} found: the CWS agent uses the Kata guest kernel mounts")
        return True

    def _use_guest_kernel_mounts(self) -> None:
        """Take the kernel filesystems from the Kata VM instead of the docker daemon's host.

        In a Kata docker-in-docker job, the docker daemon's "host" is only a container of the
        VM: --pid=host yields the DIND PID namespace, and its /sys/kernel/* are not the kernel
        filesystems the agent needs. The CI runner mounts the VM's own ones under /vm-host, as
        hostPath volumes of the job pod: on Kata, host paths under /proc and /sys resolve to the
        guest's, not the node's.
        """
        agent = self.agent_container

        # Mounts, not volumes: should the docker daemon not see /vm-host as pytest does, the agent
        # container creation fails, instead of the sources being silently created as empty dirs.
        agent.mounts = [
            Mount(target=target, source=f"{VM_HOST}/{source}", type="bind", read_only=read_only)
            for source, (target, read_only) in _GUEST_KERNEL_MOUNTS.items()
        ]

        # The agent sees cgroup files relative to the VM's namespaces, not to its own: its
        # self-cgroup detection is approximate in this topology, so it must never enforce.
        agent.environment["DD_RUNTIME_SECURITY_CONFIG_ENFORCEMENT_ENABLED"] = "false"

        self._agent_start = agent.start
        agent.start = self._agent_start_explaining_missing_mounts  # type: ignore[method-assign]

    def _agent_start_explaining_missing_mounts(self, network: Network) -> None:
        try:
            self._agent_start(network)
        except APIError as e:
            if VM_HOST not in str(e):
                raise
            message = (
                f"The agent container could not mount the Kata guest kernel filesystems ({e}). "
                f"{_GUEST_KERNEL_MOUNTS_HELP}"
            )
            # The framework logs start exceptions to tests.log only, and the console just says
            # that the agent can't be started; this is where CI users look first.
            logger.stdout(message)
            raise RuntimeError(message) from e

    def _agent_warmup_then_wait_for_cws(self) -> None:
        # Imported lazily, so that utils (which loads every scenario) does not depend on the
        # tests package at import time; this is the same readiness predicate the tests use.
        from tests.cws.utils import cws_self_test_succeeded  # noqa: PLC0415

        self._agent_warmup()

        if not interfaces.agent.wait_for(cws_self_test_succeeded, timeout=CWS_READINESS_TIMEOUT):
            message = (
                f"CWS did not report a successful self test within {CWS_READINESS_TIMEOUT}s; check the agent logs."
            )
            if self._guest_kernel_mounts:
                message += f" {_GUEST_KERNEL_MOUNTS_HELP}"
            raise RuntimeError(message)
