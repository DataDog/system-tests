"""AI Guard <-> OpenAI Responses hosted MCP tests (RFC "AI Guard MCP tool calls and extensible
connection policies", Delivery 1): MCP tool calls of the evaluated conversation carry
mcp.server_id, and the evaluate request lists the referenced servers in mcp_servers.

The cassettes are generated by utils/scripts/gen_aiguard_mcp_cassettes.py. The request bodies are
asserted through the AI Guard cassettes: their file name is a hash of the exact evaluate request
body, and each one returns a reason unique to its test and evaluation (the prompt evaluation before
the model call, the response evaluation after it). A tracer sending any other body misses the
cassette: the test agent (VCR_CI_MODE) answers with an HTTP 500, AI Guard fails open, the span has
no verdict, and the reason never shows up. Every test asserts both reasons and that no evaluation of
the test failed, so a different body for either evaluation fails the test.

The ai_guard span must report what was evaluated as well: meta_struct.ai_guard carries the messages
and, when the evaluation references MCP servers, the same mcp_servers list sent to AI Guard, so that
every mcp.server_id of the reported messages resolves to a server.
"""

