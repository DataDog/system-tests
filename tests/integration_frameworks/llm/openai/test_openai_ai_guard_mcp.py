def _prompt_reason(test_name: str) -> str:
    """Reason returned only by the cassette of the exact expected prompt evaluation of test_name."""
    return f"system-tests MCP prompt matched: {test_name}"


def _response_reason(test_name: str) -> str:
    """Reason returned only by the cassette of the exact expected response evaluation of test_name."""
    return f"system-tests MCP response matched: {test_name}"


def _create_response(
    test_client: FrameworkTestClientApi,
    input_: str | list[dict],
    tools: list[dict],
    *,
    raise_for_status: bool = True,
    **parameters: object,
) -> int:
    response = test_client.request(
        "POST",
        "/responses/create",
        dict(model=MODEL, input=input_, parameters=dict(tools=tools, **parameters)),
        raise_for_status=raise_for_status,
    )
    return response.status_code


def _one_span_with_reason(test_agent: TestAgentAPI, reason: str, target: str) -> dict:
    spans = find_ai_guard_spans_with_reason(test_agent, reason)
    assert len(spans) == 1, (
        f"expected one AI Guard evaluation returning {reason!r}, got {len(spans)}: the tracer sent a different "
        "evaluate request body (messages or mcp_servers), so the cassette did not match"
    )
    assert spans[0]["meta"]["ai_guard.target"] == target
    return spans[0]


def _matched_evaluations(
    test_agent: TestAgentAPI, request: pytest.FixtureRequest, mcp_servers: list[dict] | None
) -> tuple[list[dict], dict]:
    """Assert both evaluations of the test matched their exact expected payload, and that no other
    evaluation happened or failed open. Then assert the meta_struct of both spans reports what was
    evaluated: mcp_servers is the expected list for the response evaluation (None: not reported) and is
    never reported for the prompt evaluation, which references no MCP server.
    Returns every ai_guard span and the response evaluation span.
    """
    test_name = request.node.originalname
    prompt_span = _one_span_with_reason(test_agent, _prompt_reason(test_name), "prompt")
    response_span = _one_span_with_reason(test_agent, _response_reason(test_name), "tool")
    spans = wait_for_ai_guard_spans(test_agent, 2)
    assert len(spans) == 2, f"expected the prompt and the response evaluations only, got {len(spans)} ai_guard spans"
    for span in spans:
        assert "ai_guard.action" in span["meta"], f"an AI Guard evaluation failed open: {span['meta']}"
        assert ai_guard_messages(span), f"meta_struct.ai_guard.messages is missing: {span.get('meta_struct')}"

    assert ai_guard_mcp_servers(prompt_span) is None, "the prompt evaluation references no MCP server"
    assert ai_guard_mcp_servers(response_span) == mcp_servers, (
        "meta_struct.ai_guard.mcp_servers must report the mcp_servers sent to AI Guard"
    )
    reported_ids = {server["id"] for server in mcp_servers or []}
    for tool_call in _tool_calls(response_span):
        if "mcp" in tool_call:
            assert tool_call["mcp"]["server_id"] in reported_ids, (
                f"mcp.server_id {tool_call['mcp']['server_id']} does not resolve to a reported MCP server"
            )
    return spans, response_span


def _tool_calls(span: dict) -> list[dict]:
    return [
        tool_call
        for message in ai_guard_messages(span)
        if message.get("role") == "assistant"
        for tool_call in message.get("tool_calls") or []
    ]


def _tool_call(span: dict, name: str) -> dict:
    calls = [tool_call for tool_call in _tool_calls(span) if tool_call["function"]["name"] == name]
    assert len(calls) == 1, f"expected one {name} tool call in the AI Guard evaluation, got {_tool_calls(span)}"
    return calls[0]


def _wait_for_openai_spans(test_agent: TestAgentAPI, count: int) -> list[dict]:
    """Poll until at least count openai.request spans arrived, and return all of them (fewer on timeout)."""
    spans: list[dict] = []
    for _ in range(30):
        traces = test_agent.traces(clear=False)
        spans = [span for trace in traces for span in trace if span.get("name") == "openai.request"]
        if len(spans) >= count:
            break
        time.sleep(0.1)
    return spans


