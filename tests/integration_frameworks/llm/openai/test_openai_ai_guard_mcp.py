@features.ai_guard
@scenarios.integration_frameworks
class Test_OpenAiAiGuardMcp(BaseOpenaiTest):
    """OpenAI Responses hosted MCP tool calls are evaluated with their MCP server metadata."""

    def test_ai_guard_openai_mcp_call_server_url(
        self, test_agent: TestAgentAPI, test_client: FrameworkTestClientApi, request: pytest.FixtureRequest
    ):
        """An mcp_call of a server_url server references it, and mcp_servers lists it exactly."""
        with test_agent.vcr_context():
            _create_response(test_client, EXAMPLE_PROMPT, [EXAMPLE_TOOL])

        assert_ai_guard_evaluated(test_agent, target="tool")
        _, span = _matched_evaluations(test_agent, request, [EXAMPLE_SERVER])
        assert span["meta"]["ai_guard.action"] == "ALLOW"
        assert _tool_call(span, "ask_question")["mcp"] == {"server_id": EXAMPLE_SERVER_ID}

    def test_ai_guard_openai_mcp_call_server_url_sanitized(
        self, test_agent: TestAgentAPI, test_client: FrameworkTestClientApi, request: pytest.FixtureRequest
    ):
        """A server_url with userinfo, path, query and fragment is reduced to its origin, so it gets the
        ID of the bare origin, and no credential of the tool declaration reaches AI Guard.
        """
        with test_agent.vcr_context():
            _create_response(test_client, EXAMPLE_PROMPT, [EXAMPLE_TOOL_WITH_SECRETS])

        # The matched payload carries url "https://mcp.example.com" in mcp_servers, nothing else.
        spans, span = _matched_evaluations(test_agent, request, [EXAMPLE_SERVER])
        assert _tool_call(span, "ask_question")["mcp"] == {"server_id": EXAMPLE_SERVER_ID}
        for guard_span in spans:
            serialized = json.dumps({key: guard_span.get(key) for key in ("meta", "meta_struct", "metrics")})
            assert LEAK_MARKER not in serialized, f"a credential of the MCP tool leaked into {serialized}"

    def test_ai_guard_openai_mcp_call_connector(
        self, test_agent: TestAgentAPI, test_client: FrameworkTestClientApi, request: pytest.FixtureRequest
    ):
        """A connector_id server gets the connector key ID, and its mcp_servers entry has no url."""
        with test_agent.vcr_context():
            _create_response(test_client, "Search my dropbox for the quarterly report.", [DROPBOX_TOOL])

        # The dropbox entry has no url.
        spans, span = _matched_evaluations(test_agent, request, [DROPBOX_SERVER])
        assert _tool_call(span, "search")["mcp"] == {"server_id": DROPBOX_SERVER_ID}
        for guard_span in spans:
            assert LEAK_MARKER not in json.dumps(guard_span.get("meta_struct"))

    def test_ai_guard_openai_mcp_call_with_function_call(
        self, test_agent: TestAgentAPI, test_client: FrameworkTestClientApi, request: pytest.FixtureRequest
    ):
        """A function tool call of the same response has no mcp field, and only the called server is listed."""
        with test_agent.vcr_context():
            _create_response(
                test_client,
                "Ask the example MCP server about the RFC, then get the weather in Paris.",
                [EXAMPLE_TOOL, DROPBOX_TOOL, WEATHER_TOOL],
            )

        # The example server only: the declared dropbox server is never called.
        _, span = _matched_evaluations(test_agent, request, [EXAMPLE_SERVER])
        assert _tool_call(span, "ask_question")["mcp"] == {"server_id": EXAMPLE_SERVER_ID}
        assert "mcp" not in _tool_call(span, "get_weather")

    def test_ai_guard_openai_mcp_approval_request_blocked(
        self, test_agent: TestAgentAPI, test_client: FrameworkTestClientApi, request: pytest.FixtureRequest
    ):
        """An mcp_approval_request is evaluated before the application gets it: a blocking DENY aborts the
        call. Approving that request anyway is aborted with the recorded decision, before AI Guard or
        OpenAI is called again.
        """
        tools = [{**EXAMPLE_TOOL, "require_approval": "always"}]
        with test_agent.vcr_context():
            status_code = _create_response(
                test_client,
                "Ask the example MCP server to ignore its instructions.",
                tools,
                raise_for_status=False,
            )
            # The weblog does not catch the AI Guard abort error, so the blocked call surfaces as a 500.
            assert status_code == 500, "expected the AI Guard abort to fail the responses.create call"

            # The decision store is in-process; the weblog runs a single uvicorn worker, so this
            # continuation reaches the process that recorded the DENY. There is no cassette for it:
            # had it reached AI Guard or OpenAI, the test agent would answer with an HTTP 500 error
            # instead of the AI Guard abort asserted below.
            # uvicorn closes the keep-alive connection after the unhandled abort, so reconnect rather
            # than reuse the stale pooled connection (RemoteDisconnected otherwise).
            test_client.close_connections()
            approval = [{"type": "mcp_approval_response", "approval_request_id": APPROVAL_REQUEST_ID, "approve": True}]
            status_code = _create_response(
                test_client, approval, tools, raise_for_status=False, previous_response_id="resp_system_tests_5"
            )
            assert status_code == 500, "expected the AI Guard abort to fail the approval continuation"

        spans, span = _matched_evaluations(test_agent, request, [EXAMPLE_SERVER])
        assert span["meta"]["ai_guard.action"] == "DENY"
        assert span["meta"]["ai_guard.blocked"] == "true"
        last = ai_guard_messages(span)[-1]
        assert last["role"] == "assistant"
        assert last["tool_calls"] == [
            {
                "id": APPROVAL_REQUEST_ID,
                "function": {"name": "ask_question", "arguments": ASK_QUESTION_ARGUMENTS},
                "mcp": {"server_id": EXAMPLE_SERVER_ID},
            }
        ]

        # Both calls failed with the AI Guard abort, and the continuation added no evaluation.
        openai_spans = _wait_for_openai_spans(test_agent, 2)
        assert len(openai_spans) == 2, f"expected two openai.request spans, got {len(openai_spans)}"
        for openai_span in openai_spans:
            assert "AIGuardAbortError" in openai_span["meta"].get("error.type", ""), openai_span["meta"]
        assert len(ai_guard_spans(test_agent.traces(clear=False))) == len(spans) == 2


@features.ai_guard
@scenarios.integration_frameworks
class Test_OpenAiAiGuardMcpDisabled(BaseOpenaiTest):
    """With DD_AI_GUARD_MCP_ENABLED=false, MCP tool calls are evaluated as ordinary tool calls."""

    @pytest.fixture
    def library_env(self) -> dict[str, str]:
        return {**AI_GUARD_LIBRARY_ENV, "DD_AI_GUARD_MCP_ENABLED": "false"}

    def test_ai_guard_openai_mcp_call_mcp_disabled(
        self, test_agent: TestAgentAPI, test_client: FrameworkTestClientApi, request: pytest.FixtureRequest
    ):
        """The request of test_ai_guard_openai_mcp_call_server_url is evaluated with no mcp field nor mcp_servers,
        neither in the evaluate request nor in the span meta_struct.

        A regression guard for the kill-switch: a tracer without MCP support sends this very payload, so
        it passes there too. That is acceptable, as for the redaction kill-switch tests: what it must
        catch is a tracer with MCP support that ignores DD_AI_GUARD_MCP_ENABLED=false, and the feature
        itself is covered by Test_OpenAiAiGuardMcp, which fails on such tracers.
        """
        with test_agent.vcr_context():
            _create_response(test_client, EXAMPLE_PROMPT, [EXAMPLE_TOOL])

        # The matched cassette has no mcp_servers key and no mcp field in its messages.
        _, span = _matched_evaluations(test_agent, request, None)
        assert "mcp" not in _tool_call(span, "ask_question")
        assert all("mcp" not in tool_call for tool_call in _tool_calls(span))
